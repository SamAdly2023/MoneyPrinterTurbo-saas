"""
AI "hero clip": one short, realistic generated video (about 5 seconds) used as the opening hook of an
otherwise stock-footage video.

Generated by the open Wan 2.2 text-to-video model (Apache 2.0) as hosted on Replicate - the PrunaAI
"fast" build, `wan-video/wan-2.2-t2v-fast`. Replicate bills per clip (at the time of writing roughly
$0.05 at 480p and $0.10 at 720p - check https://replicate.com/wan-video/wan-2.2-t2v-fast for the
current price), and nothing here needs a GPU on our side. It uses the same `replicate_api_token`
platform setting as the talking-avatar feature (see avatar.py).

Official models are called by name (no version id needed), unlike the community SadTalker model.
Everything is behind generate_hero_clip() so the provider can be swapped without touching callers.
"""

import os
import time

import requests
from loguru import logger

from app.services import firestore_db

REPLICATE_MODEL = "wan-video/wan-2.2-t2v-fast"
_API = "https://api.replicate.com/v1"
_POLL_INTERVAL_SECONDS = 3
_MAX_WAIT_SECONDS = 300

# The model draws people badly (hands, faces) and renders text as gibberish, so the prompt says so.
_PROMPT_INSTRUCTIONS = (
    "Write ONE prompt for an AI text-to-video model that makes a 5-second opening shot for a short video.\n"
    "Rules: describe a single realistic, cinematic scene (subject, setting, lighting, camera movement) "
    "in 1-2 sentences, under 60 words. No people's faces or close-up hands, no text, signs, logos or "
    "captions, no split screens. Prefer places, objects, nature, machinery or wide shots of people from "
    "behind. Output only the prompt, nothing else.\n\n"
    "Video topic: {subject}\n"
    "Opening line of the narration: {opening}\n"
)


def _token() -> str:
    token = (firestore_db.get_global_settings().get("replicate_api_token") or "").strip()
    if not token:
        raise ValueError("Replicate API token is not set. Ask the admin to add it in Settings.")
    return token


def build_prompt(subject: str, opening: str = "") -> str:
    """A short visual prompt for the clip. Asks the configured LLM; falls back to a plain template so a
    flaky text service never blocks the clip."""
    fallback = (
        f"Cinematic realistic wide shot related to {subject.strip() or 'the topic'}, natural light, "
        "slow camera movement, shallow depth of field, high detail"
    )
    try:
        from app.services import llm

        text = llm._generate_response(
            _PROMPT_INSTRUCTIONS.format(subject=subject.strip(), opening=(opening or subject).strip())
        )
    except Exception as e:  # noqa: BLE001
        logger.warning(f"hero clip: LLM prompt failed ({e}); using the template prompt")
        return fallback
    text = (text or "").strip().strip('"').strip()
    if not text or text.lower().startswith("error") or len(text) > 600:
        return fallback
    return text


def generate_hero_clip(
    prompt: str,
    out_path: str,
    aspect: str = "9:16",
    resolution: str = "480p",
    smooth_to_30fps: bool = True,
) -> dict:
    """Make one clip and save it to out_path. Returns {"path", "seconds" (waiting time), "id"}.
    Raises on any failure - callers decide whether that is fatal (for a hero clip it should not be)."""
    token = _token()
    headers = {"Authorization": f"Bearer {token}", "Content-Type": "application/json"}
    body = {
        "input": {
            "prompt": prompt,
            "num_frames": 81,  # ~5 s at 16 fps; 81 is what the model is tuned for
            "frames_per_second": 16,
            "aspect_ratio": "9:16" if aspect == "9:16" else "16:9",
            "resolution": resolution if resolution in ("480p", "720p") else "480p",
            "go_fast": True,
            "interpolate_output": bool(smooth_to_30fps),
        }
    }
    started = time.time()
    resp = None
    for attempt in range(3):  # Replicate rate-limits accounts with little credit (429 + retry_after)
        resp = requests.post(f"{_API}/models/{REPLICATE_MODEL}/predictions", headers=headers, json=body, timeout=30)
        if resp.status_code != 429:
            break
        wait = 10
        try:
            wait = min(30, int(resp.json().get("retry_after", 10)))
        except Exception:  # noqa: BLE001
            pass
        logger.warning(f"hero clip: Replicate rate limit, retrying in {wait}s")
        time.sleep(wait + 1)
    if resp.status_code == 402:
        raise RuntimeError("Replicate account is out of credit - add billing credit at replicate.com/account/billing")
    if resp.status_code == 401:
        raise RuntimeError("Replicate rejected the API token (401) - check it in the admin Settings")
    resp.raise_for_status()
    prediction = resp.json()
    get_url = prediction["urls"]["get"]

    while prediction.get("status") in ("starting", "processing"):
        if time.time() - started > _MAX_WAIT_SECONDS:
            raise TimeoutError("Replicate hero clip generation timed out")
        time.sleep(_POLL_INTERVAL_SECONDS)
        poll = requests.get(get_url, headers={"Authorization": f"Bearer {token}"}, timeout=30)
        poll.raise_for_status()
        prediction = poll.json()

    if prediction.get("status") != "succeeded":
        raise RuntimeError(f"hero clip generation failed: {prediction.get('error') or prediction.get('status')}")
    output = prediction.get("output")
    video_url = output[0] if isinstance(output, list) and output else output
    if not video_url or not isinstance(video_url, str):
        raise RuntimeError("Replicate returned no output video")

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    data = requests.get(video_url, timeout=120)
    data.raise_for_status()
    with open(out_path, "wb") as f:
        f.write(data.content)
    logger.success(f"hero clip saved: {out_path} ({len(data.content) // 1024} KB, {time.time() - started:.0f}s)")
    return {"path": out_path, "seconds": time.time() - started, "id": prediction.get("id", "")}
